CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE organizations (
    org_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_name VARCHAR(255) NOT NULL,
    legal_form VARCHAR(10) NOT NULL
);

CREATE TABLE checks (
    check_id INT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    check_sum NUMERIC(10, 2) NOT NULL,
    user_id INT REFERENCES users(user_id),
    org_id INT REFERENCES organizations(org_id),
    invoice_id INT
);

CREATE TABLE items (
    item_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(255) NOT NULL,
    item_price NUMERIC(10, 2) NOT NULL,
    item_type SMALLINT NOT NULL,
    item_quantity NUMERIC(8, 3) NOT NULL,
    item_sum NUMERIC(10, 2) NOT NULL,
    check_id INT REFERENCES checks(check_id)
);

ALTER TABLE checks
ADD CONSTRAINT checks_sum_positive
CHECK (check_sum >= 0);

ALTER TABLE items
ADD CONSTRAINT items_price_positive
CHECK (item_price > 0);

ALTER TABLE items
ADD CONSTRAINT items_quantity_positive
CHECK (item_quantity > 0);

ALTER TABLE items
ADD CONSTRAINT items_sum_non_negative
CHECK (item_sum >= 0);